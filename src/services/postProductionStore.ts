export function addDeliverableComment(
  deliverableId: string,
  userName: string,
  role: string,
  content: string
): DeliverableComment {
  const all = getDeliverableCommentsMap()
  const current = all[deliverableId] || []
  const newComment: DeliverableComment = {
    id: `comm-${Date.now()}-${Math.random().toString(36).substring(2, 6)}`,
    deliverable_id: deliverableId,
    user_name: userName,
    role,
    content,
    created_at: new Date().toISOString(),
  }
  all[deliverableId] = [newComment, ...current]

  try {
    localStorage.setItem(COMMENTS_KEY, JSON.stringify(all))
    broadcastPaymentSync()
  } catch (e) {
    console.error('Error saving comment', e)
  }

  addDeliverableActivityLog(deliverableId, `New comment added by ${userName}`, userName)
  return newComment
}

export function getDeliverableComments(deliverableId: string): DeliverableComment[] {
  const all = getDeliverableCommentsMap()
  return all[deliverableId] || []
}

function getDeliverableCommentsMap(): Record<string, DeliverableComment[]> {
  try {
    const d = localStorage.getItem(COMMENTS_KEY)
    return d ? JSON.parse(d) : {}
  } catch {
    return {}
  }
}

export function getDeliverableActivityLogs(deliverableId: string): DeliverableActivityLog[] {
  try {
    const d = localStorage.getItem(LOGS_KEY)
    const map: Record<string, DeliverableActivityLog[]> = d ? JSON.parse(d) : {}
    return map[deliverableId] || []
  } catch {
    return []
  }
}

export function addDeliverableActivityLog(
  deliverableId: string,
  action: string,
  userName: string
): void {
  try {
    const d = localStorage.getItem(LOGS_KEY)
    const map: Record<string, DeliverableActivityLog[]> = d ? JSON.parse(d) : {}
    const current = map[deliverableId] || []
    const newLog: DeliverableActivityLog = {
      id: `log-${Date.now()}-${Math.random().toString(36).substring(2, 6)}`,
      deliverable_id: deliverableId,
      action,
      user_name: userName,
      timestamp: new Date().toISOString(),
    }
    map[deliverableId] = [newLog, ...current]
    localStorage.setItem(LOGS_KEY, JSON.stringify(map))
  } catch (e) {
    console.error('Error saving activity log', e)
  }
}
