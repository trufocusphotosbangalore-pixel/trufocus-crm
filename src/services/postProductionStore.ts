export function updateDeliverableAssignment(
  id: string,
  editorName: string,
  editorId?: string
): PostProductionItem | null {
  const items = getPostProductionItems()
  const idx = items.findIndex((i) => i.id === id)
  if (idx === -1) return null

  const target = items[idx]
  const previousEditor = target.assigned_editor_name
  const previousStatus = target.status

  let newStatus = target.status
  let newProgress = target.progress_percent

  if (editorName && editorName.trim().length > 0) {
    if (!previousEditor) {
      if (previousStatus === 'not_started' || previousStatus === 'pending' || previousStatus === 'assigned') {
        newStatus = 'in_progress'
        newProgress = 40
      }
      addDeliverableActivityLog(id, `Deliverable assigned to ${editorName}`, 'Manager')
      if (previousStatus !== newStatus) {
        addDeliverableActivityLog(id, `Status changed from Not Started to In Progress`, 'System')
      }
    } else if (previousEditor !== editorName) {
      if (previousStatus === 'not_started') {
        newStatus = 'in_progress'
        newProgress = 40
      }
      addDeliverableActivityLog(id, `Reassigned from ${previousEditor} to ${editorName}`, 'Manager')
    }
  } else {
    newStatus = 'not_started'
    newProgress = 0
    addDeliverableActivityLog(id, `Assignment removed`, 'Manager')
    if (previousStatus !== 'not_started') {
      addDeliverableActivityLog(id, `Status changed from ${previousStatus.replace('_', ' ').toUpperCase()} to Not Started`, 'System')
    }
  }

  const updated: PostProductionItem = {
    ...target,
    assigned_editor_name: editorName || null,
    assigned_editor_id: editorName ? (editorId || target.assigned_editor_id) : null,
    status: newStatus,
    progress_percent: newProgress,
    updated_at: new Date().toISOString(),
  }

  items[idx] = updated
  savePostProductionItems(items)
  WorkOrderWorkflowService.syncWorkOrderStatus(target.work_order_id)

  return updated
}

