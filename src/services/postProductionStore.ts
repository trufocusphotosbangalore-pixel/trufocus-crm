/**
 * Check if a Work Order's shoot has been completed.
 * Work Orders appear in Post Production ONLY when production_completed === true
 * or all production services/events are completed.
 */
export function isWorkOrderProductionCompleted(wo: WorkOrder): boolean {
  if (wo.production_completed === true) return true

  const st = (wo.status || '').toLowerCase()
  if (st === 'editing' || st === 'completed' || st === 'delivered') return true

  const prodStatus = WorkOrderWorkflowService.calculateProductionStatus(wo)
  if (prodStatus === 'completed') return true

  return false
}

/**
 * Automatically expand package services into granular post-production deliverable tasks
 * upon shoot completion.
 */
export function getAutoGeneratedDeliverableNames(wo: WorkOrder): string[] {
  const existingDeliverables = (wo.deliverables || [])
    .filter((d) => d.is_included !== false)
    .map((d) => d.name)

  if (existingDeliverables.length > 0) {
    return existingDeliverables
  }

  const generated: string[] = []
  const eventTypes = (wo.events || []).map((e) => (e.event_type_name || wo.event_type || '').toLowerCase())

  generated.push('Raw Footage & Photos Uploaded')
  generated.push('Edited Photos')
  generated.push('Social Media Photos')
  generated.push('Album Selection')
  generated.push('Album Designing')
  generated.push('Gallery Upload')

  const isVideoRequested = eventTypes.some((t) => t.includes('video') || t.includes('film') || t.includes('wedding') || t.includes('cinematic'))
  if (isVideoRequested || true) {
    generated.push('Highlight Film')
    generated.push('Instagram Reel')
    generated.push('Full Length Video')
  }

  return generated
}

/**
 * Fetch Post Production items.
 * STRICT RULE: Only Work Orders where production_completed === true appear in Post Production.
 */
export function getPostProductionItems(): PostProductionItem[] {
  let storedItems: PostProductionItem[] = []
  try {
    const data = localStorage.getItem(STORAGE_KEY)
    if (data) {
      let parsed = JSON.parse(data)
      if (parsed && typeof parsed === 'object' && !Array.isArray(parsed) && Array.isArray((parsed as any).data)) {
        parsed = (parsed as any).data
      }
      if (Array.isArray(parsed)) {
        if (parsed.length > 0 && Array.isArray(parsed[0])) {
          parsed = parsed.flat()
        }
        const valid = parsed.filter((i: any) => i && typeof i === 'object' && i.id)
        storedItems = filterOutLegacyDemoItems(valid)
        if (storedItems.length !== valid.length) {
          localStorage.setItem(STORAGE_KEY, JSON.stringify(storedItems))
        }
      }
    }
  } catch (e) {
    console.error('Error reading post production items from storage', e)
  }

  const productionCompletedWorkOrders = getLocalWorkOrders().filter(
    (w) => !w.deleted_at && w.status !== 'deleted' && isWorkOrderProductionCompleted(w)
  )

  const taskMap = new Map<string, PostProductionItem>()
  storedItems.forEach((item) => {
    if (!item) return
    if (item.id) taskMap.set(item.id, item)
    if (item.work_order_id && item.deliverable_name) {
      taskMap.set(`${item.work_order_id}_${item.deliverable_name.toLowerCase()}`, item)
    }
    if (item.work_order_number && item.deliverable_name) {
      taskMap.set(`${item.work_order_number}_${item.deliverable_name.toLowerCase()}`, item)
    }
  })

  const derivedItems: PostProductionItem[] = []
  let hasNewGeneratedItems = false

  productionCompletedWorkOrders.forEach((wo) => {
    const deliverableNames = getAutoGeneratedDeliverableNames(wo)

    deliverableNames.forEach((delName, idx) => {
      const delNameLower = delName.toLowerCase()
      const key1 = `${wo.id}_${delNameLower}`
      const key2 = `${wo.work_order_number}_${delNameLower}`
      const existing = taskMap.get(key1) || taskMap.get(key2)

      if (existing) {
        derivedItems.push({
          ...existing,
          work_order_id: wo.id,
          work_order_number: wo.work_order_number,
          customer_name: wo.customer_name || existing.customer_name,
          mobile: wo.mobile || existing.mobile,
          event_type: wo.event_type || existing.event_type,
        })
      } else {
        hasNewGeneratedItems = true
        const newItem: PostProductionItem = {
          id: `post-${wo.id}-${idx}`,
          work_order_id: wo.id,
          work_order_number: wo.work_order_number,
          customer_name: wo.customer_name,
          mobile: wo.mobile,
          event_type: wo.event_type,
          deliverable_name: delName,
          specifications: `${delName} for ${wo.customer_name} (${wo.project_name})`,
          assigned_editor_name: null,
          assigned_editor_id: null,
          priority: 'medium',
          due_date: wo.final_delivery_date || wo.album_delivery_date || new Date().toISOString().split('T')[0],
          status: 'not_started',
          progress_percent: 0,
          approval_status: 'not_sent',
          created_at: wo.created_at || new Date().toISOString(),
          updated_at: new Date().toISOString(),
        }
        derivedItems.push(newItem)
      }
    })
  })

  // Also include any custom deliverables present in storedItems that belong to active work orders
  storedItems.forEach((item) => {
    if (item && item.id && !derivedItems.some((d) => d.id === item.id)) {
      derivedItems.push(item)
    }
  })

  if (hasNewGeneratedItems && derivedItems.length > 0) {
    savePostProductionItems(derivedItems)
  }

  return derivedItems
}

