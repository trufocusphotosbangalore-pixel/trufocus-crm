// 1. Gallery Upload requires Edited Photos to be completed
export function isGalleryUploadBlocked(item: PostProductionItem, allWOItems: PostProductionItem[]): { blocked: boolean; reason?: string } {
  if (!item.deliverable_name.toLowerCase().includes('gallery upload')) {
    return { blocked: false }
  }
  const editedPhotosItem = allWOItems.find(
    (i) => i.work_order_id === item.work_order_id && i.deliverable_name.toLowerCase().includes('edited photos')
  )
  if (editedPhotosItem && editedPhotosItem.status !== 'completed' && editedPhotosItem.status !== 'delivered' && editedPhotosItem.status !== 'done') {
    return {
      blocked: true,
      reason: 'Requires "Edited Photos" to be completed before Gallery Upload can begin.',
    }
  }
  return { blocked: false }
}

// 2. Album Design requires Client Selected Photos to be completed
export function isAlbumDesignBlocked(item: PostProductionItem, allWOItems: PostProductionItem[]): { blocked: boolean; reason?: string } {
  if (!item.deliverable_name.toLowerCase().includes('album design')) {
    return { blocked: false }
  }
  const selectionItem = allWOItems.find(
    (i) => i.work_order_id === item.work_order_id && (i.deliverable_name.toLowerCase().includes('selection') || i.deliverable_name.toLowerCase().includes('edited photos'))
  )
  if (selectionItem && selectionItem.status !== 'completed' && selectionItem.status !== 'delivered' && selectionItem.status !== 'done') {
    return {
      blocked: true,
      reason: 'Requires "Album Selection" to be completed by client before Album Designing can begin.',
    }
  }
  return { blocked: false }
}

// 3. Cinematic Film / Highlight / Reel / Trailer requires Raw Footage Uploaded to be completed
export function isCinematicFilmBlocked(item: PostProductionItem, allWOItems: PostProductionItem[]): { blocked: boolean; reason?: string } {
  const name = item.deliverable_name.toLowerCase()
  if (!name.includes('highlight') && !name.includes('reel') && !name.includes('trailer') && !name.includes('full length video')) {
    return { blocked: false }
  }
  const rawFootageItem = allWOItems.find(
    (i) => i.work_order_id === item.work_order_id && i.deliverable_name.toLowerCase().includes('raw footage')
  )
  if (rawFootageItem && rawFootageItem.status !== 'completed' && rawFootageItem.status !== 'delivered' && rawFootageItem.status !== 'done') {
    return {
      blocked: true,
      reason: 'Requires "Raw Footage & Photos Uploaded" to be completed before Video Editing can begin.',
    }
  }
  return { blocked: false }
}

export function savePostProductionItems(items: PostProductionItem[]): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(items))
    pushEntityToCloud('post_production', 'main', items)
    broadcastCloudSync('post_production', items)
    broadcastPaymentSync()
    WorkOrderWorkflowService.reconcileAllLifecycles()
  } catch (e) {
    console.error('Error saving post production items to storage', e)
  }
}

export function updateDeliverableStatus(
  id: string,
  newStatus: DeliverableStatus,
  progressPercent?: number
): PostProductionItem | null {
  const items = getPostProductionItems()
  const idx = items.findIndex((i) => i.id === id)
  if (idx === -1) return null

  const target = items[idx]
  let autoProgress = progressPercent ?? target.progress_percent

  if (newStatus === 'completed' || newStatus === 'delivered' || newStatus === 'done') {
    autoProgress = 100
  } else if (newStatus === 'client_approval') {
    autoProgress = 90
  } else if (newStatus === 'ready_for_review' || newStatus === 'review' || newStatus === 'for_review') {
    autoProgress = 75
  } else if (newStatus === 'in_progress' || newStatus === 'editing') {
    autoProgress = 40
  } else if (newStatus === 'not_started' || newStatus === 'pending' || newStatus === 'assigned') {
    autoProgress = 0
  }

  const updated: PostProductionItem = {
    ...target,
    status: newStatus,
    progress_percent: autoProgress,
    delivered_date: newStatus === 'delivered' ? new Date().toISOString().split('T')[0] : target.delivered_date,
    updated_at: new Date().toISOString(),
  }

  items[idx] = updated
  savePostProductionItems(items)
  WorkOrderWorkflowService.syncWorkOrderStatus(target.work_order_id)

  addDeliverableActivityLog(
    id,
    `Status changed from ${target.status.replace('_', ' ').toUpperCase()} to ${newStatus.replace('_', ' ').toUpperCase()}`,
    'Editor'
  )

  return updated
}

